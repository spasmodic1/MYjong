const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const sharp = require('sharp');
const { _electron: electron } = require('@playwright/test');
const root = path.resolve(__dirname, '..');

test('Windows app: library, crops, matching, persistence, settings, phone upload and win', { timeout: 180000 }, async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'myjong-e2e-'));
  let application;
  t.after(async () => { await application?.close(); await fs.rm(dir, { recursive: true, force: true }); });
  const launch = async () => {
    application = await electron.launch({ args: [root], env: { ...process.env, MYJONG_TEST_DATA: dir, MYJONG_SMOKE:'1' } });
    const page = await application.firstWindow(); page.setDefaultTimeout(30000);
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForFunction(() => document.querySelector('#board .tile'));
    await page.waitForFunction(()=>document.querySelector('#board').getAttribute('aria-busy')!=='true');
    if(await page.locator('#splash-dialog[open]').count())await page.keyboard.press('Enter');
    return page;
  };
  let page = await launch(); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1366,768));
  await fs.mkdir(path.join(root,'test-results'),{recursive:true});
  await page.screenshot({path:path.join(root,'test-results','garden-1366.png')});
  const overflow = await page.evaluate(() => {
    const space=document.querySelector('#board-space').getBoundingClientRect();
    return [...document.querySelectorAll('.tile')].some(t=>{const r=t.getBoundingClientRect();return r.left<space.left || r.right>space.right || r.top<space.top || r.bottom>space.bottom;});
  });
  assert.equal(overflow,false,'tiles fit laptop viewport');
  await page.getByRole('button',{name:'Photo collection',exact:true}).click();
  console.log('Collection opened');
  const imageFile=path.join(dir,'cat.png');
  await sharp({create:{width:800,height:600,channels:3,background:'#aa9977'}}).png().toFile(imageFile);
  await application.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},imageFile);
  await page.getByRole('button',{name:'Add photos',exact:true}).click();
  console.log('Import requested');
  await page.waitForSelector('.photo-card');
  console.log('Photo imported');
  await page.getByRole('button',{name:'Add a name',exact:true}).click();
  await page.locator('#subject-name').fill('Test Cat');
  await page.getByRole('button',{name:'Save name',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#subject-dialog').open);
  const subject=await page.evaluate(async()=> (await window.myjong.library()).subjects[0].id);
  await page.locator('.photo-card select').selectOption(subject);
  await page.waitForTimeout(200);
  await page.getByRole('button',{name:'Frame photo',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#crop-image').naturalWidth>0);
  await page.locator('#crop-zoom').fill('1.5');
  await page.getByRole('button',{name:'Save crop',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#crop-dialog').open);
  await page.locator('#library-dialog [data-close]').click();
  await page.locator('#new').click(); await page.locator('#difficulty').selectOption('1');
  await page.locator('#collection').selectOption('photos'); await page.locator('#matching').selectOption('subject');
  await page.getByRole('button',{name:'Start puzzle',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#new-dialog').open);
  await page.waitForFunction(()=>document.querySelector('#board').getAttribute('aria-busy')!=='true');
  assert.ok(await page.locator('.tile-photo').count()>0);
  await page.locator('#hint').click(); assert.equal(await page.locator('.tile.hint').count(),2);
  const pair = await page.locator('.tile.hint').evaluateAll(tiles=>tiles.map(t=>t.dataset.id));
  const count = await page.locator('.tile').count();
  for(const id of pair) await page.locator(`.tile[data-id="${id}"]`).click();
  assert.equal(await page.locator('.tile').count(),count-2);
  await page.waitForTimeout(350);
  await page.reload(); await page.waitForSelector('.tile');await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('#board').getAttribute('aria-busy')!=='true');
  assert.equal(await page.locator('.tile').count(),count-2);
  await page.locator('#undo').click(); assert.equal(await page.locator('.tile').count(),count);
  await page.locator('#settings').click(); await page.locator('#theme').selectOption('plum');
  await page.locator('#settings-dialog [data-close]').click();
  await page.waitForTimeout(250); await page.reload(); await page.waitForSelector('body.plum');await page.keyboard.press('Enter');
  await page.locator('#pause').click(); assert.equal(await page.locator('#pause-dialog').isVisible(),true);
  await page.locator('#resume').click();
  // A one-subject board has a valid match along every free pair removal path.
  while(await page.locator('.tile').count()) {
    await page.locator('#hint').click();
    const ids=await page.locator('.tile.hint').evaluateAll(tiles=>tiles.map(t=>t.dataset.id));
    assert.equal(ids.length,2);
    for(const id of ids) await page.locator(`.tile[data-id="${id}"]`).click();
  }
  await page.waitForSelector('#win-dialog[open]');
  assert.match(await page.locator('#win-details').textContent(),/pairs found/);
  await page.locator('#win-dialog [data-close]').click();
  const saved = await page.evaluate(()=>window.myjong.load()); assert.equal(saved.state.stats.won,1);
  await page.locator('#photos').click(); await page.locator('#import-phone').click();
  await page.waitForSelector('#phone-dialog[open]');
  const phoneURL = await page.locator('#phone-url').textContent();
  const localURL = new URL(phoneURL); localURL.hostname='127.0.0.1';
  const response = await fetch(localURL); assert.equal(response.status,200);
  const unauth = new URL(localURL); unauth.search=''; assert.equal((await fetch(unauth)).status,403);
  const other=await sharp({create:{width:400,height:500,channels:3,background:'#1188aa'}}).jpeg().toBuffer();
  localURL.pathname='/upload'; localURL.searchParams.set('name','phone.jpg');
  assert.equal((await fetch(localURL,{method:'POST',body:other})).status,200);
  await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===2);
  await page.waitForFunction(()=>!document.querySelector('#phone-dialog').open);
  await page.locator('#library-dialog [data-close]').click();
  await page.locator('#new').click(); await page.locator('#difficulty').selectOption('3');
  await page.locator('#collection').selectOption('traditional'); await page.locator('#mode').selectOption('challenge');
  await page.getByRole('button',{name:'Start puzzle',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#new-dialog').open);
  await page.screenshot({path:path.join(root,'test-results','plum-challenging-1366.png')});
  assert.equal(errors.length,0,errors.join('\n'));
});
