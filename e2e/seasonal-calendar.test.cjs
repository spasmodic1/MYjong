const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path'),os=require('node:os');
const {_electron:electron}=require('@playwright/test'),root=path.resolve(__dirname,'..');
test('background follows the calendar and preferences while a resumed board keeps its faces',{timeout:60000},async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'myjong-season-calendar-'));
 const {makeGame,defaults,emptyStats}=await import('../src/game.js');
 const {normalizeSeasonal}=await import('../src/seasonal.js');
 const settings=normalizeSeasonal({...defaults,collection:'traditional'});
 const game=makeGame(settings,{photos:[],subjects:[]},Math.random,{theme:null,tiles:false,background:false,mix:'mixed',finish:true});
 await fs.writeFile(path.join(dir,'state.json'),JSON.stringify({version:2,settings,stats:emptyStats(),game}));
 await fs.writeFile(path.join(dir,'library.json'),JSON.stringify({version:1,photos:[],subjects:[]}));
 const app=await electron.launch({...process.env.MYJONG_TEST_PACKAGE==='1'?{executablePath:path.join(root,'dist/win-unpacked/MYjong.exe'),args:[]}:{args:[root]},env:{...process.env,MYJONG_TEST_DATA:dir,MYJONG_SMOKE:'1'}});
 t.after(async()=>{await app.close();await fs.rm(dir,{recursive:true,force:true});});
 const page=await app.firstWindow();page.setDefaultTimeout(15000);
 await page.waitForSelector('#board .tile');await page.keyboard.press('Enter');
 await page.evaluate(()=>{const Native=Date;window.testMonth=10;window.Date=class extends Native{constructor(...args){super(...(args.length?args:[2026,window.testMonth,1,12]));}};});
 await page.locator('#settings').click();await page.locator('#seasonal-heading').click();
 await page.locator('#seasonalBackground').uncheck();await page.locator('#seasonalBackground').check();
 assert.equal(await page.locator('body').getAttribute('data-background-season'),'thanksgiving');
 assert.match(await page.locator('#board-space').evaluate(el=>getComputedStyle(el).backgroundImage),/thanksgiving\.webp/);
 assert.equal(await page.locator('body').getAttribute('data-season'),'');
 assert.equal(await page.locator('#board .seasonal-face').count(),0);
 await page.evaluate(()=>window.testMonth=11);
 await page.waitForFunction(()=>document.body.dataset.backgroundSeason==='christmas',null,{timeout:15000});
 assert.match(await page.locator('#board-space').evaluate(el=>getComputedStyle(el).backgroundImage),/christmas\.webp/);
 assert.deepEqual((await page.evaluate(()=>window.myjong.load())).state.game.tiles,game.tiles);
 await page.locator('#seasonalBackground').uncheck();
 assert.equal(await page.locator('body').getAttribute('data-background-season'),'');
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('seasonal-background')),false);
});
